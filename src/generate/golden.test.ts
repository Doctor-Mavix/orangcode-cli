import { existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

import { blueprintSchema } from '../blueprint/schema';
import type { Blueprint } from '../blueprint/schema';
import {
  domainFiles,
  emitPrismaBlock,
  endMarker,
  moduleFiles,
  startMarker,
  upsertManifestModule,
  upsertPrismaRegion,
} from './index';

/**
 * The determinism proof of insight 20 §4: the emitters reproduce the showcase module of the
 * template BYTE FOR BYTE. Any drift between the generator and the hand-groomed reference
 * fails here first.
 */

/**
 * The template lives in its own repository. By default it is expected next to this one
 * (`../nodejs_express_typescript/`); `ORANGCODE_TEMPLATE_DIR` points elsewhere. Without a
 * template checkout the golden suite is skipped rather than failed.
 */
const TEMPLATE_DIR = process.env['ORANGCODE_TEMPLATE_DIR'];
const TEMPLATE_ROOT =
  TEMPLATE_DIR !== undefined && TEMPLATE_DIR !== ''
    ? `${resolve(TEMPLATE_DIR)}/`
    : fileURLToPath(new URL('../../../nodejs_express_typescript/', import.meta.url));
const TEMPLATE_AVAILABLE = existsSync(
  `${TEMPLATE_ROOT}.orangcode/blueprints/complaint.blueprint.json`,
);

function templateFile(relativePath: string): string {
  return readFileSync(`${TEMPLATE_ROOT}${relativePath}`, 'utf8');
}

function loadBlueprint(): Blueprint {
  const raw = templateFile('.orangcode/blueprints/complaint.blueprint.json');
  return blueprintSchema.parse(JSON.parse(raw));
}

describe.skipIf(!TEMPLATE_AVAILABLE)(
  'golden: complaint module is regenerated byte-identical',
  () => {
    if (!TEMPLATE_AVAILABLE) return;

    const blueprint = loadBlueprint();
    const files = [...domainFiles(blueprint), ...moduleFiles(blueprint)];

    it.each(files.map((file) => [file.path, file.content] as const))(
      '%s matches the template',
      (path, content) => {
        expect(content).toBe(templateFile(path));
      },
    );

    it('emits the prisma region exactly as it stands between the markers', () => {
      const schema = templateFile('prisma/schema.prisma');
      const start = `${startMarker('complaint')}\n`;
      const end = endMarker('complaint');
      const startIndex = schema.indexOf(start);
      const endIndex = schema.indexOf(end);

      expect(startIndex).toBeGreaterThanOrEqual(0);
      expect(endIndex).toBeGreaterThan(startIndex);

      // The region is "<start>\n\n<block>\n<end>".
      const region = schema.slice(startIndex + start.length + 1, endIndex - 1);

      expect(emitPrismaBlock(blueprint)).toBe(region);
    });

    it('rewrites prisma/schema.prisma to the identical file (idempotence)', () => {
      const schema = templateFile('prisma/schema.prisma');

      expect(upsertPrismaRegion(schema, 'complaint', emitPrismaBlock(blueprint))).toBe(schema);
    });

    it('leaves src/modules/index.ts untouched: the complaint module is already registered', () => {
      const manifest = templateFile('src/modules/index.ts');

      expect(upsertManifestModule(manifest, 'complaint')).toBe(manifest);
    });

    it('is idempotent: two runs of every emitter produce the same bytes', () => {
      const again = loadBlueprint();
      const second = [...domainFiles(again), ...moduleFiles(again)];

      files.forEach((file, index) => {
        expect(second[index]?.path).toBe(file.path);
        expect(second[index]?.content).toBe(file.content);
      });
      expect(emitPrismaBlock(blueprint)).toBe(emitPrismaBlock(loadBlueprint()));
    });
  },
);
