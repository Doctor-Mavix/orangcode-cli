import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

import { loadBlueprintFile } from '../blueprint/load';
import { blueprintSchema, formatIssuePath } from '../blueprint/schema';
import type { Blueprint } from '../blueprint/schema';
import { CliError } from '../errors';
import {
  domainFiles,
  emitPrismaBlock,
  moduleFiles,
  upsertManifestModule,
  upsertPrismaRegion,
} from '../generate';
import { readProjectManifest } from '../manifest/project-manifest';
import type { BlueprintEntry } from '../manifest/project-manifest';
import { writeOut } from '../output';
import type { Command } from './command';

const USAGE = 'Usage: orangcode doctor [--project <dir>]';

export class DoctorCommand implements Command {
  readonly name = 'doctor';
  readonly summary = 'Check that the generated files, anchors and manifest agree.';

  run(args: readonly string[]): number {
    const projectDir = parseOptions(args);
    const manifest = readProjectManifest(projectDir);
    writeOut(`Project template: ${manifest.template} v${manifest.templateVersion}`);

    if (manifest.blueprints.length === 0) {
      writeOut('No module recorded yet — nothing to check beyond the manifest itself.');
      return 0;
    }

    const problems: string[] = [];

    for (const entry of manifest.blueprints) {
      checkModule(projectDir, entry, problems);
    }

    if (problems.length === 0) {
      writeOut('Everything checks out.');
      return 0;
    }

    writeOut(`Doctor found ${problems.length} problem(s).`);
    return 1;
  }
}

function checkModule(projectDir: string, entry: BlueprintEntry, problems: string[]): void {
  const before = problems.length;
  const report = (message: string): void => {
    problems.push(message);
    writeOut(`  ${message}`);
  };
  writeOut(`module "${entry.module}":`);

  const blueprintPath = join(projectDir, entry.blueprint);

  if (!existsSync(blueprintPath)) {
    report(
      `${entry.blueprint}: missing — restore it from version control, or run ` +
        `"orangcode generate module" again from the source blueprint.`,
    );
    return;
  }

  const parsed = blueprintSchema.safeParse(loadBlueprintFile(blueprintPath));

  if (!parsed.success) {
    const issues = parsed.error.issues
      .map((issue) => `${formatIssuePath(issue.path)}: ${issue.message}`)
      .join('; ');
    report(`${entry.blueprint}: invalid blueprint (${issues}).`);
    return;
  }

  const blueprint = parsed.data;
  const expected = new Map(
    [...domainFiles(blueprint), ...moduleFiles(blueprint)].map((file) => [
      file.path,
      file.content,
    ]),
  );
  let verified = 0;

  for (const [path, content] of expected) {
    const target = join(projectDir, path);

    if (!existsSync(target)) {
      report(`${path}: missing — "orangcode regenerate" will restore it.`);
      continue;
    }

    const onDisk = readFileSync(target, 'utf8');

    if (onDisk === content) {
      verified += 1;
      continue;
    }

    const diskHash = createHash('sha256').update(onDisk).digest('hex');

    if (entry.generatedFiles[path] !== undefined && diskHash !== entry.generatedFiles[path]) {
      report(
        `${path}: edited by hand since the last generate — "orangcode regenerate" will ` +
          `overwrite it. Move the change into a hand-written file (service, controller slot).`,
      );
    } else {
      report(
        `${path}: stale — the blueprint or the generator changed. Run "orangcode regenerate".`,
      );
    }
  }

  for (const path of Object.keys(entry.generatedFiles)) {
    if (!expected.has(path)) {
      report(
        `${path}: recorded in the manifest but no longer generated by this blueprint — ` +
          `"orangcode regenerate" will refresh the manifest; delete the file if it lingers.`,
      );
    }
  }

  checkAnchors(projectDir, blueprint, report);

  if (problems.length === before) {
    writeOut(`  ok (${verified}/${expected.size} generated files verified)`);
  }
}

function checkAnchors(
  projectDir: string,
  blueprint: Blueprint,
  report: (message: string) => void,
): void {
  const name = blueprint.module.name;
  const indexPath = join(projectDir, 'src', 'modules', 'index.ts');

  if (!existsSync(indexPath)) {
    report(`src/modules/index.ts: missing — is --project pointing at the project root?`);
  } else {
    try {
      const source = readFileSync(indexPath, 'utf8');

      if (upsertManifestModule(source, name) !== source) {
        report(
          `src/modules/index.ts: module "${name}" is not registered between the markers — ` +
            `run "orangcode regenerate".`,
        );
      }
    } catch (error) {
      report(
        `src/modules/index.ts: ${error instanceof Error ? error.message : String(error)}`,
      );
    }
  }

  if (blueprint.module.supportedProviders === 'mongo') {
    return;
  }

  const prismaPath = join(projectDir, 'prisma', 'schema.prisma');

  if (!existsSync(prismaPath)) {
    report(`prisma/schema.prisma: missing — is --project pointing at the project root?`);
    return;
  }

  try {
    const source = readFileSync(prismaPath, 'utf8');

    if (upsertPrismaRegion(source, name, emitPrismaBlock(blueprint)) !== source) {
      report(
        `prisma/schema.prisma: region "${name}" is missing or out of date — ` +
          `run "orangcode regenerate".`,
      );
    }
  } catch (error) {
    report(`prisma/schema.prisma: ${error instanceof Error ? error.message : String(error)}`);
  }
}

function parseOptions(args: readonly string[]): string {
  let projectDir = process.cwd();

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];

    if (arg === '--project') {
      const value = args[index + 1];

      if (value === undefined) {
        throw new CliError(`Missing value after --project.\n${USAGE}`);
      }

      projectDir = value;
      index += 1;
    } else {
      throw new CliError(`Unexpected argument "${arg ?? ''}".\n${USAGE}`);
    }
  }

  return projectDir;
}
